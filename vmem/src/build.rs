//! Builds everything a voice agent reads, from the ledger and the
//! hand-written files in core/ and roles/.
//!
//! Outputs (generated, never edit them by hand):
//! - `packs/boot.md`: rules, where we left off, what to load next. The same
//!   text goes into the README between the `vmem:boot` markers, so opening
//!   the repo link is enough to start.
//! - `packs/brief.md`: all current memory, most important first, under a
//!   token budget, with a note of what was left out.
//! - `packs/full.md`: instructions, roles, handoff format and all memory.
//! - `packs/spoken.txt`: a recap ready to be said aloud.
//! - `packs/check.md`: questions that prove the memory was really loaded.
//! - `packs/topics/<slug>.md`: one page per project, person or topic.
//! - `packs/custom/<slug>.md`: saved task packs (`vmem context --save`).
//! - `packs/manifest.json`: version, code, sizes and hashes of every file.
//! - `memory/*.md`: readable views of the ledger, with ids.
//! - `sessions/`: one page per session, plus an index.
//! - `llms.txt`: the repo index for language models.
//!
//! Output depends only on repo content, never on the wall clock, so
//! `vmem build --check` gives the same answer on any machine, any day.

