/// Tokens kept free at the end of a budgeted pack for the "left out" note.
const FOOTER: usize = 60;

fn note() -> String {
    "<!-- Generated by vmem from memory/ledger.jsonl. Do not edit by hand: change memory with vmem (see AGENTS.md), then run `vmem build`. -->\n".to_string()
}

