/// One topic page, found by slug, name, alias or a misheard name.
pub fn topic_for(repo: &Repo, name: &str) -> Result<String, String> {
    let ctx = Ctx::new(repo)?;
    let slug = slugify(name);
    if let Some(t) = ctx.topics.iter().find(|t| t.slug == slug) {
        return Ok(ctx.topic_page(t).trim_end().to_string());
    }
    let idx = EntityIndex::from_state(&repo.state);
    if let Some(e) = idx.best(name) {
        if let Some(t) = ctx.topics.iter().find(|t| t.slug == e.slug) {
            return Ok(ctx.topic_page(t).trim_end().to_string());
        }
    }
    let known: Vec<&str> = ctx.topics.iter().map(|t| t.slug.as_str()).collect();
    Err(format!(
        "no topic called {name:?}. Known topics: {}",
        if known.is_empty() { "none yet".to_string() } else { known.join(", ") }
    ))
}

fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n")
}

fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
    let Ok(rd) = fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = rd.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            walk(root, &p, out);
        } else if let Ok(rel) = p.strip_prefix(root) {
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
}

/// Files in generator-owned folders that are no longer produced.
fn stale(root: &Path, out: &Output) -> Vec<String> {
    let mut found = Vec::new();
    for dir in OWNED_DIRS {
        walk(root, &root.join(dir), &mut found);
    }
    found.retain(|rel| !out.files.contains_key(rel));
    found.sort();
    found
}

/// What differs between the generated output and the disk.
pub fn drift(root: &Path, out: &Output) -> Vec<String> {
    let mut v = Vec::new();
    for (rel, content) in &out.files {
        match fs::read_to_string(root.join(rel)) {
            Ok(cur) if normalize(&cur) == *content => {}
            Ok(_) => v.push(format!("changed: {rel}")),
            Err(_) => v.push(format!("missing: {rel}")),
        }
    }
    for rel in stale(root, out) {
        v.push(format!("stale: {rel}"));
    }
    v
}

/// Writes changed files and removes stale ones. Returns what changed.
pub fn write(root: &Path, out: &Output) -> Result<Vec<String>, String> {
    let mut changed = Vec::new();
    for (rel, content) in &out.files {
        let path = root.join(rel);
        let same = fs::read_to_string(&path).map(|c| normalize(&c) == *content).unwrap_or(false);
        if same {
            continue;
        }
        if let Some(d) = path.parent() {
            fs::create_dir_all(d).map_err(|e| format!("cannot create {}: {e}", d.display()))?;
        }
        fs::write(&path, content).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
        changed.push(rel.clone());
    }
    for rel in stale(root, out) {
        fs::remove_file(root.join(&rel)).map_err(|e| format!("cannot remove {rel}: {e}"))?;
        changed.push(format!("{rel} (removed)"));
    }
    Ok(changed)
}
